func TestRankYouTubePageVideosKeepsLegitUploads(t *testing.T) {
	cases := []struct {
		name   string
		query  lyrics.Query
		videos []media.Track
		wantID string
	}{
		{
			name:  "official audio upload",
			query: lyrics.Query{Title: "BLOODLUST", Artist: "Dysmn"},
			videos: []media.Track{
				{ID: "yt:vVFq7Fwyzlg", Title: "BLOODLUST - Dysmn (Official Audio)", Artists: []media.Ref{{Name: "Dysmn"}}},
			},
			wantID: "vVFq7Fwyzlg",
		},
		{
			name:  "lyrics upload",
			query: lyrics.Query{Title: "nikon", Artist: "guardin"},
			videos: []media.Track{
				{ID: "yt:abc12345678", Title: "guardin - nikon [Lyrics]", Artists: []media.Ref{{Name: "LyricArchive"}}},
			},
			wantID: "abc12345678",
		},
		{
			name:  "kanji romaji english lyrics upload",
			query: lyrics.Query{Title: "Idol", Artist: "YOASOBI"},
			videos: []media.Track{
				{ID: "yt:idol1234567", Title: "YOASOBI - Idol (Kanji/Romaji/English Lyrics)", Artists: []media.Ref{{Name: "JPopLyrics"}}},
			},
			wantID: "idol1234567",
		},
		{
			name:  "cover art video",
			query: lyrics.Query{Title: "Idol", Artist: "YOASOBI"},
			videos: []media.Track{
				{ID: "yt:art12345678", Title: "YOASOBI - Idol (Cover Art)", Artists: []media.Ref{{Name: "Archive"}}},
			},
			wantID: "art12345678",
		},
		{
			name:  "explicitly requested cover track",
			query: lyrics.Query{Title: "My Song (Cover)", Artist: "Singer"},
			videos: []media.Track{
				{ID: "yt:cov12345678", Title: "My Song (Cover) - Singer", Artists: []media.Ref{{Name: "Fan"}}},
			},
			wantID: "cov12345678",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := rankYouTubePageVideos(tc.videos, tc.query, map[string]bool{})
			if len(got) != 1 || got[0].vid != tc.wantID {
				t.Fatalf("rankYouTubePageVideos = %+v, want vid %q", got, tc.wantID)
			}
		})
	}
}

func TestIsDerivativeVideoDescription(t *testing.T) {
	espadaDesc := "Thank you for listening!\n\n" +
		"First off, I do not claim any ownership of the music used in this video; this is my commentary on what I believe vocals would sound like over this absolute MONSTER of a song.\n" +
		"You can listen to the original instrumental song on Spotify.\n\nLyrics:\nA secret can be loosed in a minute\n"
	if !isDerivativeVideoDescription("Espada (feat. Spiro)", espadaDesc) {
		t.Fatal("expected derivative description disclaimer to be detected")
	}
	if isDerivativeVideoDescription("Espada (Vocal Cover)", espadaDesc) {
		t.Fatal("should not reject when track title explicitly mentions Vocal Cover")
	}
	normalDesc := "Official lyric video for nikon by guardin.\n\nLyrics:\ncan someone please just turn the lights down\n"
	if isDerivativeVideoDescription("nikon", normalDesc) {
		t.Fatal("normal lyric description should not be flagged as derivative")
	}
}
