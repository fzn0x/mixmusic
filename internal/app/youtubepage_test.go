func TestYouTubePageLookupFromPinnedCommentAndDescription(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/youtubei/v1/search":
			w.Write([]byte(`{"contents":{"twoColumnSearchResultsRenderer":{"primaryContents":{"sectionListRenderer":{"contents":[{"itemSectionRenderer":{"contents":[
				{"videoRenderer":{"videoId":"ytOfficial","title":{"runs":[{"text":"guardin - nikon"}]},"ownerText":{"runs":[{"text":"guardin"}]},"lengthText":{"simpleText":"2:28"}}},
				{"videoRenderer":{"videoId":"ytLyricVid","title":{"runs":[{"text":"guardin - nikon (Lyrics)"}]},"ownerText":{"runs":[{"text":"Static"}]},"lengthText":{"simpleText":"2:27"}}}
			]}}]}}}}}`))
		case "/youtubei/v1/player":
			var body map[string]any
			_ = json.NewDecoder(r.Body).Decode(&body)
			switch body["videoId"] {
			case "ytTopic":
				w.Write([]byte(`{"videoDetails":{"videoId":"ytTopic","title":"nikon","author":"guardin - Topic","lengthSeconds":"146","shortDescription":"Provided to YouTube by DistroKid\n\nnikon\n\nAuto-generated by YouTube."}}`))
			case "ytOfficial":
				w.Write([]byte(`{"videoDetails":{"videoId":"ytOfficial","title":"guardin - nikon","author":"guardin","lengthSeconds":"148","shortDescription":"follow guardin\nhttps://instagram.com/guardin"}}`))
			case "ytLyricVid":
				desc := "Follow:\nhttps://example.com\n\nLyrics for \"nikon\" by guardin:\nline from description one\nline from description two\nline from description three\nline from description four\nline from description five\nline from description six"
				resp, _ := json.Marshal(map[string]any{"videoDetails": map[string]any{"videoId": "ytLyricVid", "title": "guardin - nikon (Lyrics)", "author": "Static", "lengthSeconds": "147", "shortDescription": desc}})
				w.Write(resp)
			default:
				w.WriteHeader(http.StatusNotFound)
			}
		case "/youtubei/v1/next":
			var body map[string]any
			_ = json.NewDecoder(r.Body).Decode(&body)
			if body["continuation"] == "tok-official" {
				w.Write([]byte(`{
					"onResponseReceivedEndpoints":[{"reloadContinuationItemsCommand":{"continuationItems":[
						{"commentThreadRenderer":{"comment":{"commentViewModel":{"commentKey":"c1","pinnedText":{"content":"Pinned"}}}}}
					]}}],
					"frameworkUpdates":{"entityBatchUpdate":{"mutations":[{"payload":{"commentEntityPayload":{
						"key":"c1",
						"properties":{"content":{"content":"lyrics\n--------\npinned line one\npinned line two\npinned line three\npinned line four\npinned line five\npinned line six"}},
						"author":{"displayName":"@guardinmusic","isCreator":true}
					}}}]}}
				}`))
				return
			}
			if body["videoId"] == "ytOfficial" {
				w.Write([]byte(`{"contents":{"twoColumnWatchNextResults":{"results":{"results":{"contents":[
					{"itemSectionRenderer":{"sectionIdentifier":"comment-item-section","contents":[
						{"continuationItemRenderer":{"continuationEndpoint":{"continuationCommand":{"token":"tok-official"}}}}
					]}}
				]}}}}}`))
				return
			}
			w.Write([]byte(`{}`))
		default:
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	defer srv.Close()

	ls := newLyricsSources(t)
	withPicks(t, ls)
	ls.c.a.youtube = youtube.New()
	ls.c.a.youtube.BaseURL = srv.URL

	var srcs []settings.LyricsSource
	for _, k := range settings.LyricsSourceKeys {
		srcs = append(srcs, settings.LyricsSource{Key: k, Off: k != settings.LyricsYouTubePage})
	}
	withSources(t, ls, false, srcs...)

	track := media.Track{
		ID: "yt:ytTopic", Source: media.SourceYouTube, Title: "nikon",
		Artists: []media.Ref{{Name: "guardin"}}, DurationMs: 146000,
	}
	l, err := ls.c.Lyrics(context.Background(), track)
	if err != nil {
		t.Fatalf("Lyrics: %v", err)
	}
	if l.Source != YouTubePageSource || l.Lines[0].Text != "pinned line one" || !strings.Contains(l.SourceURL, "ytOfficial") {
		t.Errorf("got = %+v", l)
	}

	cands := ls.c.SearchLyrics(context.Background(), track, "nikon", "guardin")
	if len(cands) != 2 {
		t.Fatalf("SearchLyrics got %d candidates, want 2: %+v", len(cands), cands)
	}
	if cands[0].Lyrics.Lines[0].Text != "pinned line one" || cands[1].Lyrics.Lines[0].Text != "line from description one" {
		t.Errorf("unexpected candidates: %+v, %+v", cands[0], cands[1])
	}
}

func TestYouTubePageBilingualCommentAndEditRoundTrip(t *testing.T) {
	bilingual := strings.Join([]string{
		"Lyrics",
		"",
		"Jimen ni hizamazuki, namida ni nureru,",
		"Awaremi motome, jibun no kachi wo inoru,",
		"Demo kotae wa shizuka, yabureta sakebi ni,",
		"Aoi sora kara hashigo wa orite konai.",
		"Eien ni ten no tobira wa hirakanai,",
		"Ushinawareta tenshi zutto eien ni.",
		"",
		"============================",
		"",
		"English:",
		"",
		"Kneeling on the ground, drenched in tears,",
		"Seeking compassion, praying for my worth,",
		"But the answer is silent, in a broken cry,",
		"From the blue sky, no ladder will descend.",
		"The gates of heaven will never open,",
		"The lost angel, forever and ever.",
	}, "\n")

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/youtubei/v1/player":
			w.Write([]byte(`{"videoDetails":{"videoId":"ytBi01","title":"BLOODLUST","author":"Dysmn","lengthSeconds":"267","shortDescription":"links"}}`))
		case "/youtubei/v1/next":
			var body map[string]any
			_ = json.NewDecoder(r.Body).Decode(&body)
			if body["continuation"] == "tok-bi" {
				resp, _ := json.Marshal(map[string]any{
					"onResponseReceivedEndpoints": []any{map[string]any{
						"reloadContinuationItemsCommand": map[string]any{
							"continuationItems": []any{map[string]any{"commentThreadRenderer": map[string]any{"comment": map[string]any{"commentViewModel": map[string]any{"commentKey": "c1"}}}}},
						},
					}},
					"frameworkUpdates": map[string]any{"entityBatchUpdate": map[string]any{"mutations": []any{map[string]any{
						"payload": map[string]any{"commentEntityPayload": map[string]any{
							"key":        "c1",
							"properties": map[string]any{"content": map[string]any{"content": bilingual}},
							"author":     map[string]any{"displayName": "@goat5480"},
						}},
					}}}},
				})
				w.Write(resp)
				return
			}
			w.Write([]byte(`{"contents":{"twoColumnWatchNextResults":{"results":{"results":{"contents":[
				{"itemSectionRenderer":{"sectionIdentifier":"comment-item-section","contents":[
					{"continuationItemRenderer":{"continuationEndpoint":{"continuationCommand":{"token":"tok-bi"}}}}
				]}}
			]}}}}}`))
		default:
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	defer srv.Close()

	ls := newLyricsSources(t)
	withPicks(t, ls)
	ls.c.a.youtube = youtube.New()
	ls.c.a.youtube.BaseURL = srv.URL
	var srcs []settings.LyricsSource
	for _, k := range settings.LyricsSourceKeys {
		srcs = append(srcs, settings.LyricsSource{Key: k, Off: k != settings.LyricsYouTubePage})
	}
	withSources(t, ls, false, srcs...)

	track := media.Track{ID: "yt:ytBi01", Source: media.SourceYouTube, Title: "BLOODLUST", Artists: []media.Ref{{Name: "Dysmn"}}, DurationMs: 267000}
	l, err := ls.c.Lyrics(context.Background(), track)
	if err != nil {
		t.Fatalf("Lyrics: %v", err)
	}
	if l.Language != "ja" || l.Translation == nil || l.Translation.From != "ja" || l.Translation.To != "en" || len(l.Lines) != 6 {
		t.Fatalf("expected bilingual ja->en lyrics, got lang=%q lines=%d tr=%+v", l.Language, len(l.Lines), l.Translation)
	}
	if l.Lines[0].Text != "Jimen ni hizamazuki, namida ni nureru," || l.Translation.Lines[0].Text != "Kneeling on the ground, drenched in tears," {
		t.Fatalf("unexpected row 0: %+v / %+v", l.Lines[0], l.Translation.Lines[0])
	}

	edited, err := ls.c.EditLyrics(track, l.LRC(), l)
	if err != nil {
		t.Fatalf("EditLyrics: %v", err)
	}
	if edited.Translation == nil || edited.Translation.To != "en" || edited.Translation.Lines[5].Text != "The lost angel, forever and ever." {
		t.Fatalf("EditLyrics dropped embedded translation: %+v", edited.Translation)
	}
	reloaded, err := ls.c.Lyrics(context.Background(), track)
	if err != nil || reloaded.Translation == nil || reloaded.Language != "ja" {
		t.Fatalf("reloaded picked bilingual lyrics failed: %+v, %v", reloaded, err)
	}
}

