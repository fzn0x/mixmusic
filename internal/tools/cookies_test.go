// TestMain runs the test binary as a fake yt-dlp when a test asks: it then
// exports cookies as fakeYTDLP says, and never reads a browser.
func TestMain(m *testing.M) {
	if mode := os.Getenv("MIXMUSIC_FAKE_YTDLP"); mode != "" {
		os.Exit(fakeYTDLP(mode, os.Args[1:]))
	}
	os.Exit(m.Run())
}

// fakeJar is a jar the fake yt-dlp writes, of made-up cookies.
const fakeJar = ".youtube.com\tTRUE\t/\tTRUE\t0\tSAPISID\tmadeup\n"

// fakeYTDLP acts as yt-dlp exporting a browser's cookies, as mode says: it
// keeps its arguments in MIXMUSIC_FAKE_ARGS, and checks the cookies file
// as yt-dlp loads it before it writes it.
func fakeYTDLP(mode string, args []string) int {
	if f := os.Getenv("MIXMUSIC_FAKE_ARGS"); f != "" {
		os.WriteFile(f, []byte(strings.Join(args, "\n")), 0o600)
	}
	file := ""
	if i := slices.Index(args, "--cookies"); i >= 0 && i+1 < len(args) {
		file = args[i+1]
	}
	if data, err := os.ReadFile(file); err == nil && !strings.HasPrefix(string(data), "# Netscape HTTP Cookie File") {
		fmt.Fprintf(os.Stderr, "ERROR: '%s' does not look like a Netscape format cookies file\n", file)
		return 1
	}
	switch mode {
	case "export", "undecrypted":
		fmt.Println("Extracting cookies from firefox")
		if mode == "undecrypted" {
			fmt.Println("Extracted 3 cookies from chrome (2 could not be decrypted)")
		}
		os.WriteFile(file, []byte(NetscapeHeader+"# This file is generated by yt-dlp.  Do not edit.\n\n"+fakeJar), 0o600)
		fmt.Fprintln(os.Stderr, "Usage: yt-dlp [OPTIONS] URL [URL...]\n\nyt-dlp: error: You must provide at least one URL.")
		return 2
	case "dpapi":
		for range 2 {
			fmt.Fprintln(os.Stderr, "ERROR: Failed to decrypt with DPAPI. See  https://github.com/yt-dlp/yt-dlp/issues/10927  for more info")
		}
	case "locked":
		fmt.Fprintln(os.Stderr, "ERROR: Could not copy Chrome cookie database. See  https://github.com/yt-dlp/yt-dlp/issues/7271  for more info")
	case "missing":
		fmt.Fprintln(os.Stderr, `ERROR: could not find firefox cookies database in 'C:\nowhere'`)
	case "other":
		fmt.Fprintln(os.Stderr, "ERROR: [Cookies] something else went wrong")
	}
	return 1
}

// fakeManager is a manager whose yt-dlp is the fake one, acting as mode
// says.
func fakeManager(t *testing.T, mode string) (*Manager, string) {
	t.Helper()
	self, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("MIXMUSIC_FAKE_YTDLP", mode)
	args := filepath.Join(t.TempDir(), "args")
	t.Setenv("MIXMUSIC_FAKE_ARGS", args)
	m := New(t.TempDir())
	m.Configure(self, "")
	return m, args
}

// cookiesFile is a file for the cookies, as the caller makes it.
func cookiesFile(t *testing.T) string {
	t.Helper()
	f := filepath.Join(t.TempDir(), "cookies.txt")
	if err := os.WriteFile(f, []byte(NetscapeHeader), 0o600); err != nil {
		t.Fatal(err)
	}
	return f
}

// TestCookiesFromBrowser takes the cookies yt-dlp wrote, though it exits
// with an error for want of a video.
func TestCookiesFromBrowser(t *testing.T) {
	m, argsFile := fakeManager(t, "export")
	file := cookiesFile(t)
	undecrypted, err := m.CookiesFromBrowser(context.Background(), "firefox:C:\\Profiles\\x.default::none", file)
	if err != nil || undecrypted {
		t.Fatalf("CookiesFromBrowser = %v, %v", undecrypted, err)
	}
	data, _ := os.ReadFile(file)
	if !strings.Contains(string(data), "SAPISID\tmadeup") {
		t.Errorf("the file holds %q", data)
	}
	args, _ := os.ReadFile(argsFile)
	want := []string{"--ignore-config", "--no-progress", "--cookies-from-browser", "firefox:C:\\Profiles\\x.default::none", "--cookies", file}
	if got := strings.Split(string(args), "\n"); !slices.Equal(got, want) {
		t.Errorf("yt-dlp ran with %q, want %q", got, want)
	}

	// An empty file is not one yt-dlp reads.
	empty := filepath.Join(t.TempDir(), "empty.txt")
	os.WriteFile(empty, nil, 0o600)
	if _, err := m.CookiesFromBrowser(context.Background(), "firefox", empty); err == nil || !strings.Contains(err.Error(), "Netscape") {
		t.Errorf("an empty file gave %v", err)
	}
}

func TestCookiesFromBrowserUndecrypted(t *testing.T) {
	m, _ := fakeManager(t, "undecrypted")
	if undecrypted, err := m.CookiesFromBrowser(context.Background(), "chrome", cookiesFile(t)); err != nil || !undecrypted {
		t.Errorf("CookiesFromBrowser = %v, %v; want the undecrypted cookies told", undecrypted, err)
	}
}

// TestCookiesFromBrowserErrors tells why yt-dlp could not read a browser,
// in the reasons the app words for the user.
func TestCookiesFromBrowserErrors(t *testing.T) {
	for mode, want := range map[string]error{
		"dpapi":   ErrCookiesSealed,
		"locked":  ErrBrowserOpen,
		"missing": ErrNoBrowserCookies,
	} {
		m, _ := fakeManager(t, mode)
		if _, err := m.CookiesFromBrowser(context.Background(), "chrome", cookiesFile(t)); !errors.Is(err, want) {
			t.Errorf("%s: %v, want %v", mode, err, want)
		}
	}
	m, _ := fakeManager(t, "other")
	if _, err := m.CookiesFromBrowser(context.Background(), "chrome", cookiesFile(t)); err == nil || err.Error() != "yt-dlp: something else went wrong" {
		t.Errorf("another error: %v", err)
	}
}

func TestCookiesFromBrowserWithoutYTDLP(t *testing.T) {
	t.Setenv("PATH", "")
	m := New(t.TempDir())
	if _, err := m.CookiesFromBrowser(context.Background(), "firefox", cookiesFile(t)); !errors.Is(err, ErrNoYTDLP) {
		t.Errorf("without yt-dlp: %v", err)
	}
}

func TestErrorLine(t *testing.T) {
	stderr := "WARNING: a warning\nERROR: [youtube] abc: first\nERROR: [youtube] abc: Video unavailable\nnoise\n"
	if got := ErrorLine(stderr); got != "abc: Video unavailable" {
		t.Errorf("ErrorLine = %q", got)
	}
	if got := ErrorLine("Usage: yt-dlp\n\nyt-dlp: error: You must provide at least one URL."); got != "" {
		t.Errorf("a usage error gave %q", got)
	}
}
