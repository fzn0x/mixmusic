package youtube

import (
	"context"
	"strconv"
	"strings"
	"time"
)

// VideoComment holds one YouTube video comment's author, provenance, and text.
type VideoComment struct {
	Author    string
	Text      string
	IsCreator bool
	IsPinned  bool
}

// VideoLyricsContext holds the description and top comments of a YouTube video.
type VideoLyricsContext struct {
	VideoID     string
	Title       string
	Author      string
	Duration    time.Duration
	Description string
	Comments    []VideoComment
}

// VideoLyricsContext fetches a YouTube video's title, author, description,
// and top comments anonymously using the YouTube web InnerTube client.
func (c *Client) VideoLyricsContext(ctx context.Context, videoID string) (VideoLyricsContext, error) {
	videoID = strings.TrimSpace(videoID)
	if videoID == "" {
		return VideoLyricsContext{}, ErrNotFound
	}
	opts := callOptions{baseURL: c.webOrigin(), anonymous: true}
	p, err := c.callWith(ctx, webClient, "player", map[string]any{"videoId": videoID}, nil, opts)
	if err != nil {
		return VideoLyricsContext{}, err
	}
	vd := p.get("videoDetails")
	out := VideoLyricsContext{
		VideoID:     videoID,
		Title:       vd.get("title").str(),
		Author:      vd.get("author").str(),
		Description: vd.get("shortDescription").str(),
	}
	if secs, err := strconv.ParseInt(vd.get("lengthSeconds").str(), 10, 64); err == nil && secs > 0 {
		out.Duration = time.Duration(secs) * time.Second
	}
	if isAutoTopicDesc(out.Description) {
		return out, nil
	}
	nx, err := c.callWith(ctx, webClient, "next", map[string]any{"videoId": videoID}, nil, opts)
	if err != nil {
		// Keep the description even if comments could not be loaded.
		return out, nil
	}
	tok := findCommentsContinuation(nx)
	if tok == "" {
		return out, nil
	}
	cm, err := c.callWith(ctx, webClient, "next", map[string]any{"continuation": tok}, nil, opts)
	if err != nil {
		return out, nil
	}
	out.Comments = parseVideoComments(cm)
	return out, nil
}

func isAutoTopicDesc(desc string) bool {
	d := strings.TrimSpace(strings.ReplaceAll(desc, "\r\n", "\n"))
	return strings.HasPrefix(d, "Provided to YouTube by ") && strings.HasSuffix(d, "Auto-generated by YouTube.")
}

func findCommentsContinuation(n node) string {
	var sections []any
	var collect func(v any, depth int)
	collect = func(v any, depth int) {
		if depth <= 0 {
			return
		}
		switch v := v.(type) {
		case map[string]any:
			if v["targetId"] == "comments-section" || v["sectionIdentifier"] == "comment-item-section" {
				sections = append(sections, v)
				return
			}
			for _, x := range v {
				collect(x, depth-1)
			}
		case []any:
			for _, x := range v {
				collect(x, depth-1)
			}
		}
	}
	collect(n.v, 24)
	for _, sec := range sections {
		if tok := (node{sec}).find("continuationCommand").get("token").str(); tok != "" {
			return tok
		}
	}
	return ""
}

func parseVideoComments(n node) []VideoComment {
	pinnedKeys := map[string]bool{}
	var walkModels func(v any, depth int)
	walkModels = func(v any, depth int) {
		if depth <= 0 {
			return
		}
		switch v := v.(type) {
		case map[string]any:
			if m, ok := v["commentViewModel"].(map[string]any); ok {
				vm := node{m}
				if vm.get("pinnedText").exists() {
					if key := vm.get("commentKey").str(); key != "" {
						pinnedKeys[key] = true
					}
				}
			}
			for _, x := range v {
				walkModels(x, depth-1)
			}
		case []any:
			for _, x := range v {
				walkModels(x, depth-1)
			}
		}
	}
	walkModels(n.v, 24)

	var comments []VideoComment
	var walkPayloads func(v any, depth int)
	walkPayloads = func(v any, depth int) {
		if depth <= 0 || len(comments) >= 20 {
			return
		}
		switch v := v.(type) {
		case map[string]any:
			if raw, ok := v["commentEntityPayload"].(map[string]any); ok {
				cp := node{raw}
				text := strings.TrimSpace(cp.get("properties", "content", "content").str())
				if text != "" {
					key := cp.get("key").str()
					comments = append(comments, VideoComment{
						Author:    cp.get("author", "displayName").str(),
						Text:      text,
						IsCreator: cp.get("author", "isCreator").boolean(),
						IsPinned:  key != "" && pinnedKeys[key],
					})
				}
				return
			}
			for _, x := range v {
				walkPayloads(x, depth-1)
			}
		case []any:
			for _, x := range v {
				walkPayloads(x, depth-1)
			}
		}
	}
	walkPayloads(n.v, 24)
	return comments
}
