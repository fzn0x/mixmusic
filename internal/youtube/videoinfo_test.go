func TestVideoLyricsContextPinnedAndTopic(t *testing.T) {
	nextCalls := 0
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/youtubei/v1/player" {
			var body map[string]any
			_ = json.NewDecoder(r.Body).Decode(&body)
			switch body["videoId"] {
			case "topic1":
				w.Write([]byte(`{"videoDetails":{"videoId":"topic1","title":"nikon","author":"guardin - Topic","lengthSeconds":"146","shortDescription":"Provided to YouTube by DistroKid\n\nnikon\n\nAuto-generated by YouTube."}}`))
			default:
				w.Write([]byte(`{"videoDetails":{"videoId":"vid1","title":"guardin - nikon","author":"guardin","lengthSeconds":"148","shortDescription":"follow me\nhttps://example.com"}}`))
			}
			return
		}
		if r.URL.Path == "/youtubei/v1/next" {
			nextCalls++
			var body map[string]any
			_ = json.NewDecoder(r.Body).Decode(&body)
			if body["continuation"] == "tok-comments" {
				w.Write([]byte(`{
					"onResponseReceivedEndpoints":[
						{"reloadContinuationItemsCommand":{"continuationItems":[
							{"commentThreadRenderer":{"comment":{"commentViewModel":{"commentKey":"c1","pinnedText":{"content":"Pinned by guardin"}}}}}
						]}}
					],
					"frameworkUpdates":{"entityBatchUpdate":{"mutations":[
						{"payload":{"commentEntityPayload":{"key":"c1","properties":{"content":{"content":"lyrics\n---\nline one\nline two"}},"author":{"displayName":"@guardinmusic","isCreator":true}}}},
						{"payload":{"commentEntityPayload":{"key":"c2","properties":{"content":{"content":"fire song"}},"author":{"displayName":"@fan","isCreator":false}}}}
					]}}
				}`))
				return
			}
			w.Write([]byte(`{"contents":{"twoColumnWatchNextResults":{"results":{"results":{"contents":[
				{"itemSectionRenderer":{"sectionIdentifier":"comment-item-section","contents":[
					{"continuationItemRenderer":{"continuationEndpoint":{"continuationCommand":{"token":"tok-comments"}}}}
				]}}
			]}}}}}`))
			return
		}
		w.WriteHeader(http.StatusNotFound)
	}))
	defer srv.Close()

	c := New()
	c.BaseURL = srv.URL

	topic, err := c.VideoLyricsContext(context.Background(), "topic1")
	if err != nil {
		t.Fatalf("topic: %v", err)
	}
	if topic.Duration != 146*time.Second || len(topic.Comments) != 0 || nextCalls != 0 {
		t.Fatalf("topic = %+v, nextCalls=%d (expected 0)", topic, nextCalls)
	}

	info, err := c.VideoLyricsContext(context.Background(), "vid1")
	if err != nil {
		t.Fatalf("vid1: %v", err)
	}
	if info.Title != "guardin - nikon" || info.Duration != 148*time.Second || len(info.Comments) != 2 {
		t.Fatalf("info = %+v", info)
	}
	if !info.Comments[0].IsCreator || !info.Comments[0].IsPinned || info.Comments[0].Author != "@guardinmusic" {
		t.Errorf("comment[0] = %+v", info.Comments[0])
	}
	if info.Comments[1].IsCreator || info.Comments[1].IsPinned {
		t.Errorf("comment[1] = %+v", info.Comments[1])
	}
}

func TestLiveVideoLyricsContext(t *testing.T) {
	if os.Getenv("MIXMUSIC_LIVE") == "" {
		t.Skip("set MIXMUSIC_LIVE=1 to query YouTube")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	info, err := New().VideoLyricsContext(ctx, "T2iREHVxfc8")
	if err != nil {
		t.Fatalf("VideoLyricsContext: %v", err)
	}
	found := false
	for _, cm := range info.Comments {
		if _, _, ok := lyrics.ExtractFromComment(cm.Text, cm.IsCreator, cm.IsPinned); ok {
			found = true
			t.Logf("extracted pinned comment by %s (%d comments total)", cm.Author, len(info.Comments))
			break
		}
	}
	if !found {
		t.Fatalf("no lyrics extracted from T2iREHVxfc8 comments (%d comments)", len(info.Comments))
	}
}
