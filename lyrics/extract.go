package lyrics

import (
	"regexp"
	"slices"
	"strings"
)

var (
	urlLineRe       = regexp.MustCompile(`https?://|www\.`)
	chapterStampRe  = regexp.MustCompile(`^\s*\d{1,2}:\d{2}(?::\d{2})?(?:\s+|$)`)
	sectionHeaderRe = regexp.MustCompile(`^\[(?:verse|chorus|pre-chorus|post-chorus|bridge|hook|intro|outro|refrain|breakdown)[^\]]*\]$`)
	lyricsForRe     = regexp.MustCompile(`^(?:lyrics\s*(?:for|to|of|:|-|\|)\b.*|full\s+lyrics:?|song\s+lyrics:?|lyrics\s*:?)$`)
)

// CleanLyricsText normalizes line endings, exotic Unicode spaces (e.g. U+2005,
// U+205F), divider rules, and blank-line runs into clean lyric text.
func CleanLyricsText(raw string) string {
	raw = strings.ReplaceAll(raw, "\r\n", "\n")
	raw = strings.ReplaceAll(raw, "\r", "\n")
	raw = strings.ReplaceAll(raw, "\u2028", "\n")
	raw = strings.ReplaceAll(raw, "\u2029", "\n")

	var b strings.Builder
	b.Grow(len(raw))
	for _, r := range raw {
		switch {
		case r == '\u200b' || r == '\u200c' || r == '\u200d' || r == '\ufeff':
			// drop zero-width marks
		case r == '\u00a0' || r == '\u1680' || (r >= '\u2000' && r <= '\u200a') || r == '\u202f' || r == '\u205f' || r == '\u3000':
			b.WriteByte(' ')
		default:
			b.WriteRune(r)
		}
	}

	rawLines := strings.Split(b.String(), "\n")
	cleaned := make([]string, 0, len(rawLines))
	blankRun := 0
	for _, line := range rawLines {
		line = strings.TrimSpace(line)
		if line == "" {
			if len(cleaned) > 0 && blankRun == 0 {
				cleaned = append(cleaned, "")
			}
			blankRun++
			continue
		}
		if isHashtagLine(line) || urlLineRe.MatchString(strings.ToLower(line)) {
			continue
		}
		line = stripTrailingHashtags(line)
		if line == "" {
			continue
		}
		blankRun = 0
		cleaned = append(cleaned, line)
	}
	for len(cleaned) > 0 && (cleaned[0] == "" || isDividerLine(cleaned[0])) {
		cleaned = cleaned[1:]
	}
	for len(cleaned) > 0 && (cleaned[len(cleaned)-1] == "" || isDividerLine(cleaned[len(cleaned)-1])) {
		cleaned = cleaned[:len(cleaned)-1]
	}
	return strings.Join(cleaned, "\n")
}

// IsAutoTopicDescription reports whether desc is a YouTube auto-generated
// Topic track description (no lyrics).
func IsAutoTopicDescription(desc string) bool {
	d := strings.TrimSpace(CleanLyricsText(desc))
	return strings.HasPrefix(d, "Provided to YouTube by ") && strings.HasSuffix(d, "Auto-generated by YouTube.")
}

// ExtractFromDescription pulls clean lyric lines from a YouTube video
// description when present, scoring higher when an explicit lyrics header
// introduces the block.
func ExtractFromDescription(desc string) (text string, score int, ok bool) {
	if IsAutoTopicDescription(desc) {
		return "", 0, false
	}
	normed := CleanLyricsText(desc)
	if normed == "" {
		return "", 0, false
	}
	lines := strings.Split(normed, "\n")

	if idx, inline, found := findLyricsHeader(lines); found {
		var body []string
		if inline != "" {
			body = append(body, inline)
		} else if sectionHeaderRe.MatchString(strings.ToLower(lines[idx])) {
			body = append(body, lines[idx])
		}
		for _, line := range lines[idx+1:] {
			if isDividerLine(line) && len(body) == 0 {
				continue
			}
			if isPromoStopLine(line) && nonEmptyCount(body) >= 4 {
				break
			}
			body = append(body, line)
		}
		body = trimFooterNoise(body)
		if nonEmpty := nonEmptyLines(body); looksLikeLyrics(nonEmpty, false) {
			txt := CleanLyricsText(strings.Join(body, "\n"))
			if txt != "" {
				return txt, 80 + min(len(nonEmpty), 40), true
			}
		}
	}

	// Fallback without explicit header: collect the best contiguous run of
	// non-promo, non-URL lyric paragraphs.
	paras := strings.Split(normed, "\n\n")
	var bestRun []string
	var curRun []string
	flush := func() {
		if nonEmptyCount(curRun) > nonEmptyCount(bestRun) {
			bestRun = curRun
		}
		curRun = nil
	}
	for _, p := range paras {
		pLines := strings.Split(strings.TrimSpace(p), "\n")
		if isNoiseParagraph(pLines) {
			flush()
			continue
		}
		if len(curRun) > 0 {
			curRun = append(curRun, "")
		}
		curRun = append(curRun, pLines...)
	}
	flush()

	bestRun = trimFooterNoise(bestRun)
	if nonEmpty := nonEmptyLines(bestRun); looksLikeLyrics(nonEmpty, true) {
		txt := CleanLyricsText(strings.Join(bestRun, "\n"))
		if txt != "" {
			return txt, 45 + min(len(nonEmpty), 30), true
		}
	}
	return "", 0, false
}

// ExtractFromComment extracts lyrics from a YouTube comment, requiring
// stronger evidence for regular viewer comments than pinned/creator ones.
func ExtractFromComment(comment string, isCreator, isPinned bool) (text string, score int, ok bool) {
	normed := CleanLyricsText(comment)
	if normed == "" {
		return "", 0, false
	}
	lines := strings.Split(normed, "\n")
	if !isCreator && !isPinned && hasFanWrittenDisclaimer(lines) {
		return "", 0, false
	}
	hasHeader := false
	if idx, inline, found := findLyricsHeader(lines); found && idx <= 2 {
		hasHeader = true
		var next []string
		if inline != "" {
			next = append(next, inline)
		} else if sectionHeaderRe.MatchString(strings.ToLower(lines[idx])) {
			next = append(next, lines[idx])
		}
		next = append(next, lines[idx+1:]...)
		lines = next
	}
	for len(lines) > 0 && (lines[0] == "" || isDividerLine(lines[0]) || isPromoStopLine(lines[0])) {
		lines = lines[1:]
	}
	var filtered []string
	for _, line := range lines {
		if isHashtagLine(line) || urlLineRe.MatchString(strings.ToLower(line)) {
			continue
		}
		if isPromoStopLine(line) && nonEmptyCount(filtered) >= 4 {
			break
		}
		filtered = append(filtered, line)
	}
	lines = trimFooterNoise(filtered)
	nonEmpty := nonEmptyLines(lines)
	requireStrict := !(isCreator || isPinned) && !hasHeader
	if !looksLikeLyrics(nonEmpty, requireStrict) {
		return "", 0, false
	}
	txt := CleanLyricsText(strings.Join(lines, "\n"))
	if txt == "" {
		return "", 0, false
	}
	sc := 30 + min(len(nonEmpty), 40)
	if isCreator && isPinned {
		sc += 40
	} else if isCreator {
		sc += 25
	} else if isPinned {
		sc += 15
	}
	if hasHeader {
		sc += 25
	}
	return txt, sc, true
}

func hasFanWrittenDisclaimer(lines []string) bool {
	disclaimers := []string{
		"i wrote lyrics",
		"made up lyrics",
		"fan lyrics",
		"fan-made lyrics",
		"vocal interpretation",
		"if this had lyrics",
		"if this song had lyrics",
	}
	checked := 0
	for _, line := range lines {
		low := strings.ToLower(strings.TrimSpace(line))
		if low == "" {
			continue
		}
		for _, phrase := range disclaimers {
			if strings.Contains(low, phrase) {
				return true
			}
		}
		checked++
		if checked >= 3 || strings.HasPrefix(low, "lyrics:") {
			break
		}
	}
	return false
}

func findLyricsHeader(lines []string) (idx int, inline string, ok bool) {
	for i, line := range lines {
		low := strings.ToLower(strings.TrimSpace(line))
		if low == "" {
			continue
		}
		if sectionHeaderRe.MatchString(low) {
			return i, "", true
		}
		if strings.HasPrefix(low, "lyrics:") {
			rest := strings.TrimSpace(line[len("lyrics:"):])
			return i, rest, true
		}
		if lyricsForRe.MatchString(low) {
			return i, "", true
		}
	}
	return 0, "", false
}

func trimFooterNoise(lines []string) []string {
	for len(lines) > 0 {
		last := strings.TrimSpace(lines[len(lines)-1])
		if last == "" || isDividerLine(last) || isPromoStopLine(last) {
			lines = lines[:len(lines)-1]
			continue
		}
		break
	}
	return lines
}

func isNoiseParagraph(lines []string) bool {
	if len(lines) == 0 {
		return true
	}
	urlLines := 0
	promoLines := 0
	for _, l := range lines {
		if urlLineRe.MatchString(strings.ToLower(l)) {
			urlLines++
		}
		if isPromoStopLine(l) {
			promoLines++
		}
	}
	return urlLines > 0 || promoLines > 0
}

func isPromoStopLine(line string) bool {
	low := strings.ToLower(strings.TrimSpace(line))
	if low == "" {
		return false
	}
	if urlLineRe.MatchString(low) {
		return true
	}
	prefixes := []string{
		"follow ", "instagram", "twitter", "x -", "spotify", "soundcloud",
		"apple music", "facebook", "tiktok", "discord", "merch", "subscribe",
		"produced by", "prod.", "prod by", "mixed by", "mastered by",
		"directed by", "visuals", "anime", "stream ", "support ", "supporr ",
		"listen ", "download ", "copyright", "©", "℗", "all rights reserved",
		"submit your", "business", "contact:", "email:",
		"hope this helps", "let me know if", "correct me if", "if i missed",
		"credit:", "credits:", "edit:", "thanks for", "like if", "thumbs up",
		"sub to", "check out my", "song:", "artist:", "track:", "album:",
		"tags:", "lyrics by", "transcribed by",
		"composer", "arranger", "illustration", "animation",
		"vocal:", "vocals:", "guitar:", "bass:", "drums:", "mix:", "mastering:", "movie:",
	}
	for _, p := range prefixes {
		if strings.HasPrefix(low, p) {
			return true
		}
	}
	return isHashtagLine(line)
}

// isHashtagLine reports whether line consists purely of hashtags (even a single
// tag like "#guardin") or predominantly of hashtags (>= 2 tags covering at least
// half the words on the line).
func isHashtagLine(line string) bool {
	fields := strings.Fields(strings.TrimSpace(line))
	if len(fields) == 0 {
		return false
	}
	hashes, hasWordTag := 0, false
	for _, f := range fields {
		if strings.HasPrefix(f, "#") && len(f) > 1 {
			hashes++
			for _, r := range f[1:] {
				if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') {
					hasWordTag = true
					break
				}
			}
		}
	}
	if hashes == len(fields) && hasWordTag {
		return true
	}
	return hashes >= 2 && hashes*2 >= len(fields)
}

// stripTrailingHashtags removes hashtag tokens glued onto the end of a lyric
// line (for example "lines here #guardin #lyrics") without altering numbered
// references like "#1".
func stripTrailingHashtags(line string) string {
	fields := strings.Fields(line)
	if len(fields) <= 1 {
		return line
	}
	end := len(fields)
	trailing := 0
	for end > 0 && strings.HasPrefix(fields[end-1], "#") {
		tag := fields[end-1][1:]
		letters := 0
		for _, r := range tag {
			if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') {
				letters++
			}
		}
		if letters == 0 {
			break
		}
		trailing++
		end--
	}
	if trailing >= 2 || (trailing == 1 && len(fields[len(fields)-1]) >= 4) {
		return strings.Join(fields[:end], " ")
	}
	return line
}

func isDividerLine(line string) bool {
	s := strings.TrimSpace(line)
	if len([]rune(s)) < 3 {
		return false
	}
	for _, r := range s {
		if !strings.ContainsRune("-=_*~—•·", r) {
			return false
		}
	}
	return true
}

func nonEmptyLines(lines []string) []string {
	out := make([]string, 0, len(lines))
	for _, l := range lines {
		if t := strings.TrimSpace(l); t != "" && !isDividerLine(t) {
			out = append(out, t)
		}
	}
	return out
}

func nonEmptyCount(lines []string) int {
	n := 0
	for _, l := range lines {
		if strings.TrimSpace(l) != "" {
			n++
		}
	}
	return n
}

func looksLikeLyrics(lines []string, strict bool) bool {
	minLines := 6
	if strict {
		minLines = 12
	}
	if len(lines) < minLines || len(lines) > 450 {
		return false
	}
	lengths := make([]int, len(lines))
	totalChars := 0
	urls, stamps, longLines, inRange, proseSentences, creditLines := 0, 0, 0, 0, 0, 0
	for i, l := range lines {
		n := displayWidth(l)
		lengths[i] = n
		totalChars += n
		if n >= 8 && n <= 65 {
			inRange++
		}
		if n > 95 {
			longLines++
		}
		low := strings.ToLower(strings.TrimSpace(l))
		if low == "featuring" || low == "tracklist" || low == "setlist" ||
			strings.Contains(low, "first album") || strings.Contains(low, "lead single") || strings.Contains(low, "break it all down") {
			return false
		}
		if isCreditMetadataLine(low) {
			creditLines++
		}
		if strings.HasSuffix(strings.TrimSpace(l), ".") && len(strings.Fields(l)) >= 10 {
			proseSentences++
		}
		if urlLineRe.MatchString(low) {
			urls++
		}
		if chapterStampRe.MatchString(l) {
			stamps++
		}
	}
	if urls*10 > len(lines) || stamps*3 > len(lines) || proseSentences*10 >= len(lines)*3 || creditLines*10 >= len(lines)*3 {
		return false
	}
	mean := float64(totalChars) / float64(len(lines))
	if mean < 8 || mean > 90 {
		return false
	}
	slices.Sort(lengths)
	median := lengths[len(lengths)/2]
	if median > 75 {
		return false
	}
	if strict && (longLines > 0 || float64(inRange)/float64(len(lines)) < 0.70) {
		return false
	}
	return true
}

func isCreditMetadataLine(low string) bool {
	head, _, hasColon := strings.Cut(low, ":")
	if !hasColon {
		head, _, hasColon = strings.Cut(low, "：")
	}
	if !hasColon {
		return false
	}
	head = strings.TrimSpace(head)
	if head == "" || len(head) > 36 {
		return false
	}
	roles := []string{
		"music", "composer", "arranger", "arrange", "prod", "producer",
		"vocal", "vocals", "singer", "guitar", "bass", "drum", "piano",
		"mix", "master", "illust", "art", "movie", "video", "animation",
		"director", "directed", "edit", "tuning", "lyric", "words",
	}
	for _, r := range roles {
		if strings.Contains(head, r) {
			return true
		}
	}
	return false
}

// displayWidth counts CJK/Hangul ideographs and kana as width 2 so short
// Japanese, Korean, or Chinese lyric lines score fairly alongside Latin text.
func displayWidth(s string) int {
	w := 0
	for _, r := range s {
		if (r >= 0x3040 && r <= 0x30ff) || (r >= 0x4e00 && r <= 0x9fff) || (r >= 0xac00 && r <= 0xd7af) || (r >= 0xff01 && r <= 0xff60) {
			w += 2
		} else {
			w++
		}
	}
	return w
}
