func TestCleanLyricsTextAndTopicCheck(t *testing.T) {
	raw := "\r\n  can someone\u2005please\u205fjust turn the lights down  \r\n\r\n\r\n\r\nsecond\u00a0line\r\n---\r\n"
	got := CleanLyricsText(raw)
	want := "can someone please just turn the lights down\n\nsecond line"
	if got != want {
		t.Fatalf("CleanLyricsText = %q, want %q", got, want)
	}

	topic := "Provided to YouTube by DistroKid\n\nnikon (feat. farewell, tomorrow) · guardin\n\nAuto-generated by YouTube."
	if !IsAutoTopicDescription(topic) {
		t.Error("expected IsAutoTopicDescription true")
	}
	if _, _, ok := ExtractFromDescription(topic); ok {
		t.Error("topic description should not extract lyrics")
	}
}

func TestExtractFromDescriptionAndComment(t *testing.T) {
	desc := "Spotify Playlists:\nhttps://example.com/pl\n\ninstagram - https://instagram.com/guardin\n\n" +
		"Lyrics for \"nikon\" by guardin:\n" +
		"can someone please just turn the lights down\n" +
		"i'm just tryna see you\u2005not through\u205fthe phone\n" +
		"i got your picture in my nikon\n" +
		"flash hit my face until my life's gone\n" +
		"somebody turn the lights down\n" +
		"i wanna see the way you take control\n\n" +
		"Produced by seye\nhttps://example.com/outro"

	text, sc, ok := ExtractFromDescription(desc)
	if !ok || sc < 80 {
		t.Fatalf("ExtractFromDescription failed: ok=%v, sc=%d, text=%q", ok, sc, text)
	}
	if !strings.HasPrefix(text, "can someone please") || !strings.HasSuffix(text, "take control") {
		t.Errorf("unexpected extracted bounds: %q", text)
	}
	if strings.Contains(text, "instagram") || strings.Contains(text, "Produced by") {
		t.Errorf("promo/credit lines leaked into lyrics: %q", text)
	}

	pinned := "lyrics\r\n--------\r\nline one here\r\nline two here\r\nline three here\r\nline four here\r\nline five here\r\nline six here\r\n"
	cText, cScore, ok := ExtractFromComment(pinned, true, true)
	if !ok || cScore < 100 || strings.Contains(cText, "----") || strings.HasPrefix(cText, "lyrics") {
		t.Fatalf("ExtractFromComment pinned failed: ok=%v, score=%d, text=%q", ok, cScore, cText)
	}

	if _, _, ok := ExtractFromComment("<3", true, true); ok {
		t.Error("short pinned comment should not match")
	}
	if _, _, ok := ExtractFromComment("this song is amazing\ni love guardin\nbest track of the year honestly", false, false); ok {
		t.Error("short fan comment should not match")
	}

	commentWithTags := "Lyrics:\n" +
		"can someone please just turn the lights out\n" +
		"i\u2019m passive with my steps we\u2019re always on thin ice now #guardin #lyrics\n" +
		"how can a ghost live in your head so many years\n" +
		"i still sit under this tower when the lights off\n" +
		"somebody turn the lights down\n" +
		"i wanna see the way you take control\n" +
		"#guardin #nikon #sadrap\n" +
		"Hope this helps! Let me know if I missed anything\n"
	tagText, _, ok := ExtractFromComment(commentWithTags, false, false)
	if !ok {
		t.Fatal("expected fan comment with lyrics + hashtags to extract")
	}
	if strings.Contains(tagText, "#guardin") || strings.Contains(tagText, "#lyrics") || strings.Contains(tagText, "Hope this helps") {
		t.Fatalf("hashtags or comment chatter leaked: %q", tagText)
	}
	if !strings.Contains(tagText, "i\u2019m passive with my steps we\u2019re always on thin ice now") {
		t.Fatalf("expected verbatim apostrophe line, got %q", tagText)
	}

	djSetDesc := "Skrillex has finally dropped Quest for Fire, his first album in 9 years, and the lead single \"Rumble\" featuring Fred Again, Four Tet, and Flowdan took everyone by surprise.\n\n" +
		"To make sense of the mixture of sounds and influences on the track - ranging from Grime to Jersey Club - we called in a squad of top DJs to break it all down for us.\n\n" +
		"Featuring\n\nDJ Wonder\n\nJFuse\n\nGetlive!\n\nLuv\n\nSteph Cakes\n\nE-Stylez\n"
	if _, _, ok := ExtractFromDescription(djSetDesc); ok {
		t.Fatalf("editorial DJ-set description should not extract as lyrics")
	}

	cjkComment := strings.Join([]string{
		"地面に跪き", "涙に濡れる", "憐れみ求め", "自分の価値", "でも答えは", "青い空から",
		"Kneeling down", "Drenched in", "Seeking pity", "My own worth", "The answer", "From the sky",
	}, "\n")
	if _, _, ok := ExtractFromComment(cjkComment, false, false); !ok {
		t.Fatalf("expected short-rune CJK bilingual comment to extract under strict display width check")
	}

	fanCoverComment := "I wrote lyrics for this instrumental track!\n" +
		"Lyrics:\n" +
		"line one of fan lyrics here\n" +
		"line two of fan lyrics here\n" +
		"line three of fan lyrics here\n" +
		"line four of fan lyrics here\n" +
		"line five of fan lyrics here\n" +
		"line six of fan lyrics here\n"
	if _, _, ok := ExtractFromComment(fanCoverComment, false, false); ok {
		t.Fatalf("viewer comment advertising fan-written lyrics should not extract")
	}

	creditListComment := strings.Join([]string{
		"Composer / Arranger / Prod. : PinocchioP",
		"Vocal: Hatsune Miku",
		"Illustration: PinocchioP",
		"Movie: PinocchioP",
		"Guitar: Guest Player",
		"Bass: Guest Bassist",
		"Drums: Guest Drummer",
		"Mix: Studio Engineer",
		"Mastering: Mastering Lab",
		"Tuning: Vocaloid Producer",
		"Video Edit: Editor Name",
		"Director: MV Director",
	}, "\n")
	if _, _, ok := ExtractFromComment(creditListComment, false, false); ok {
		t.Fatalf("production credit list comment should not extract as lyrics")
	}
}
